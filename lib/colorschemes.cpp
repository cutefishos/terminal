static constexpr size_t kDefaultScheme = 10;
static_assert(kSchemes[kDefaultScheme].name == "TokyoNight");

std::span<const ColorScheme> colorSchemes()
{
    return kSchemes;
}

const ColorScheme& colorScheme(std::string_view name)
{
    for (const ColorScheme& scheme : kSchemes) {
        if (scheme.name == name)
            return scheme;
    }
    return kSchemes[kDefaultScheme];
}

